// `en` is declared with literal types (handy for catching typos while
// writing it), but fr.ts/rw.ts need to assign plain `string`/`string[]` —
// this widens the literal-typed shape so other locales are checked for
// matching *structure*, not matching *English text*.
type Widen<T> = T extends readonly string[]
    ? readonly string[]
    : T extends string
      ? string
      : { [K in keyof T]: Widen<T[K]> };

export default en;
export type Strings = Widen<typeof en>;
